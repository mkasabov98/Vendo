    // Analytics orders — already have dates in analyticsSpecs
    await Promise.all(analyticsOrders.map((o, idx) => backdate("Orders", o.id, analyticsSpecs[idx].date)));

    console.log("Backdating complete.");

    // ── Summary ────────────────────────────────────────────────────────────
    console.log("\nDone!");
